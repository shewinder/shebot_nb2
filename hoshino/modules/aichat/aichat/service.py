"""aichat Service 单点定义

供命令模块（commands/）共享，避免各模块各自创建 Service。
"""
from hoshino import Service

sv = Service('aichat', help_='''AI聊天插件
基础用法：
  #消息   以#开头触发AI对话
  进入对话模式   进入免#触发模式
  退出对话模式/结束对话模式  退出连续对话模式
  查看对话模式  查看当前模式状态
对话管理：
  清除对话/清空对话/重置对话/清除上下文/清空上下文  清除当前对话历史
  回溯/回退 [N]  回溯N条对话
  查询token/token查询  查询当前会话的 Token 使用情况
人格设置：
  设置人格 [描述]  设置当前人格
  使用人格 [名称]  使用已保存的人格
  保存人格 [名称] [描述]  保存人格
  列出人格  查看已保存的人格
  查看人格  查看当前生效的人格
  清除人格  清除用户人格设置
API/模型管理：
  当前模型  查看当前API厂商和模型
  切换API [厂商名]  切换API厂商，无参数时列出可用厂商（超管）
  切换模型  进入模型切换流程，自动获取可用模型列表（超管）
工具功能（需要模型支持 Tool Calling）：
  支持画图、搜索、定时任务等工具调用
  注意：在 config 中设置 supports_tools=true 启用
定时任务（通过AI对话创建）：
  说"帮我创建一个定时任务，每天早上8点..."即可
  AI会自动调用 schedule_task 工具创建
  支持：创建/查看/暂停/删除任务
角色卡：
  导入角色卡 [图片]  从PNG角色卡导入人格
  导入全局角色卡 [图片]  导入全局预设人格（超管）
预设人格（超管）：
  预设人格 [名称] [描述]  添加/更新预设人格
  预设人格列表  列出全局预设人格
  删除预设人格 [名称]  删除预设人格
SKILL 系统：
  #使用 <skill名称>  激活指定 SKILL
  #技能列表  列出所有可用 SKILL
  #当前技能  查看已激活的 SKILL
  #停用技能 <skill名称>  停用指定 SKILL
  #停用所有技能  停用所有 SKILL
''')
